/* Dados sintéticos somente interceptados neste navegador de teste, nunca no servidor. */
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const fs = require('node:fs');
const baseURL = process.env.BASE_URL || 'http://127.0.0.1:8000';
const output = process.env.SCREENSHOT_DIR;
(async () => {
  const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || undefined, args:['--no-sandbox','--disable-dev-shm-usage']});
  const page = await browser.newPage({viewport:{width:1440,height:1080}});
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  await page.goto(baseURL);
  await page.getByText('Seu painel está pronto para receber dados').waitFor();
  assert.equal(await page.locator('h1').innerText(), 'O jogo, pelos números.');
  assert.equal(await page.locator('.game').count(), 0);
  assert.match(await page.locator('#notice').innerText(), /API_FOOTBALL_KEY/);
  if (output) { fs.mkdirSync(output,{recursive:true}); await page.screenshot({path:`${output}/painel-desktop.png`,fullPage:true}); }
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false);
  if (output) await page.screenshot({path:`${output}/painel-celular.png`,fullPage:true});
  await page.goto(`${baseURL}/docs`);
  await page.getByRole('heading',{name:'API da aplicação',exact:true}).waitFor();
  const now = new Date().toISOString();
  const fixture = {id:1, kickoff:new Date(Date.now()+86400000).toISOString(),status:'NS',league:{id:71,name:'Liga sintética de teste',country:'Teste',season:2026},home:{id:1,name:'Equipe teste <img src=x onerror=alert(1)>'},away:{id:2,name:'Equipe teste visitante'},venue:'Estádio sintético de teste',source:'API-Football v3',fixture_fetched_at:now,history_fetched_at:now,analyzed_at:now,started:false,warnings:[],injuries:null,detailed_stats:null,analysis:{model_version:'test-only',confidence:'moderada',sample:{league:100,home_venue:10,away_venue:10},home_recent:{sample:10,form:['V','E','D'],goals_for:1.2,goals_against:1,fixture_ids:[]},away_recent:{sample:10,form:['D','V','E'],goals_for:1.1,goals_against:1.3,fixture_ids:[]},h2h:[],rates:{home:1.4,away:1.1},limitations:['Dados de teste isolados.'],probabilities:{home:.52,draw:.26,away:.22,'over_2.5':.48,'under_2.5':.52,btts_yes:.51}},opportunities:[{market:'home',label:'Vitória da casa',bookmaker:'Casa sintética de teste',odd:2.1,probability:.52,fair_odd:1/.52,implied_probability:1/2.1,no_vig_probability:.5,overround:.05,expected_value:.092,sensitivity_ev:.008,updated_at:now,classification:'vantagem na sensibilidade',confidence:'moderada',eligible:true,stale:false}]};
  const snapshot={fixtures:[fixture],configured:true,stale:false,refreshing:false,updated_at:now,timezone:'America/Sao_Paulo',refresh_minutes:30,last_attempt:{status:'success'},quota:{used:4,limit:90},integration:{odds:true},warnings:[],window_start:'2026-10-09',window_end:'2026-10-12'};
  await page.route('**/api/dashboard',route=>route.fulfill({json:snapshot}));
  await page.goto(baseURL);
  await page.locator('.game').waitFor();
  assert.equal(await page.locator('#opportunities').innerText(),'1');
  assert.equal(await page.locator('.game img').count(),0,'Provider strings must be escaped');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false);
  await page.locator('summary').click();
  assert.equal(await page.locator('table tbody tr').count(),1);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false);
  await page.locator('#bookmaker').selectOption('Casa sintética de teste');
  assert.equal(await page.locator('.best').count(),1);
  await page.locator('#market').selectOption('draw');
  await page.locator('#only-value').check();
  assert.equal(await page.locator('.game').count(),0);
  await page.locator('#clear').click();
  assert.equal(await page.locator('.game').count(),1);
  await page.locator('#search').fill('inexistente');
  assert.equal(await page.locator('.game').count(),0);
  await page.locator('#clear').click();
  snapshot.stale=true; snapshot.fixtures[0].opportunities[0].eligible=false; snapshot.fixtures[0].opportunities[0].stale=true;
  await page.locator('#reload').click();
  await page.waitForFunction(()=>document.querySelector('#opportunities').textContent==='0');
  assert.equal(await page.locator('.best').count(),0);
  await page.setViewportSize({width:1440,height:1080});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false);
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('Browser OK: desktop, celular, documentação, escape de dados, filtros e odds inelegíveis.');
})().catch(error=>{console.error(error);process.exit(1);});
